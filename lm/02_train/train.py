"""
Training script for the Spanish KeyboardLM (FMAboard).

Two modes:

  Base training (from scratch on the Spanish corpus):
      python 02_train/train.py

  Fine-tuning an existing model on new text (e.g. your own messages):
      python 02_train/train.py --init 02_train/checkpoints/best.pt \
          --data path/to/personal_train.txt --valid path/to/personal_valid.txt \
          --epochs 3 --lr 1e-4 --warmup 50 --out 02_train/personal

Interrupted runs continue from the newest checkpoint with --resume.
Runs on NVIDIA CUDA (also ROCm / MPS / CPU as in the upstream pipeline).
"""
import argparse
import math
import os
import sys
import time
from pathlib import Path

import torch
from torch.optim import AdamW

sys.path.insert(0, str(Path(__file__).parent))

from model import KeyboardLM, ModelConfig  # noqa: E402
from dataset import make_loader  # noqa: E402

# ---------------------------------------------------------------------------
# Config
# ---------------------------------------------------------------------------
PROCESSED_DIR = Path(__file__).parent.parent / "01_data" / "processed"
TOKENIZER_DIR = Path(__file__).parent.parent / "01_data" / "tokenizer"
SP_MODEL = TOKENIZER_DIR / "es_keyboard.model"

# Correction-format training data (generated by 01_data/make_correction_data.py
# from the plain corpus). Falls back to plain text if it hasn't been generated.
CORRECTION_DATA = PROCESSED_DIR / "correction_train.txt"
TRAIN_DATA = CORRECTION_DATA if CORRECTION_DATA.exists() else PROCESSED_DIR / "train.txt"
VALID_DATA = PROCESSED_DIR / "valid.txt"

DEFAULT_OUT = Path(__file__).parent / "checkpoints"

TRAIN_CONFIG = dict(
    # Batches are sized in tokens (padded length × lines) and grouped by
    # length, so padding is small. On an 8 GB card 8k tokens stays in VRAM
    # (~39k tok/s on an RTX 4060 Ti); 16k spills into shared memory on
    # Windows and runs 3x slower.
    max_tokens=8192,
    max_seq_len=256,
    lr=6e-4,
    min_lr=3e-5,
    weight_decay=0.1,
    grad_clip=1.0,
    epochs=2,
    log_every=200,
    save_every=5000,
    valid_every=10000,
    valid_batches=200,
    warmup_steps=1000,
    bf16=True,
)

# ~42M params, same scale as the official FUTO ml4 model (512 embd, 8 layers).
MODEL_CONFIG = ModelConfig(
    vocab_size=16_000,
    n_layer=8,
    n_head=8,
    n_embd=512,
    max_seq_len=256,
    dropout=0.1,
)


def get_device() -> torch.device:
    if torch.cuda.is_available():
        dev = torch.device("cuda")
        print(f"GPU: {torch.cuda.get_device_name(0)}")
    elif torch.backends.mps.is_available():
        dev = torch.device("mps")
        print("GPU: Apple Metal (MPS)")
    else:
        dev = torch.device("cpu")
        print("WARNING: No GPU found, training on CPU will be very slow")
    return dev


def cosine_lr(step: int, warmup: int, total: int, max_lr: float, min_lr: float) -> float:
    if step < warmup:
        return max_lr * step / warmup
    progress = min((step - warmup) / max(total - warmup, 1), 1.0)
    return min_lr + 0.5 * (max_lr - min_lr) * (1 + math.cos(math.pi * progress))


@torch.no_grad()
def evaluate(model, loader, device, amp_ctx, max_batches: int) -> float:
    model.eval()
    total, n = 0.0, 0
    for x, y in loader:
        x = x.to(device, non_blocking=True)
        y = y.to(device, non_blocking=True)
        with amp_ctx:
            _, loss = model(x, targets=y)
        total += loss.item()
        n += 1
        if n >= max_batches:
            break
    model.train()
    return total / max(n, 1)


def latest_checkpoint(out_dir: Path) -> Path | None:
    ckpts = sorted(out_dir.glob("step_*.pt"))
    return ckpts[-1] if ckpts else None


def train(args) -> None:
    out_dir = Path(args.out)
    out_dir.mkdir(parents=True, exist_ok=True)

    cfg = dict(TRAIN_CONFIG)
    if args.epochs is not None:
        cfg["epochs"] = args.epochs
    if args.lr is not None:
        cfg["lr"] = args.lr
        cfg["min_lr"] = args.lr / 20
    if args.warmup is not None:
        cfg["warmup_steps"] = args.warmup
    if args.max_tokens is not None:
        cfg["max_tokens"] = args.max_tokens

    device = get_device()
    torch.backends.cuda.matmul.allow_tf32 = True
    torch.backends.cudnn.allow_tf32 = True

    use_bf16 = cfg["bf16"] and torch.cuda.is_available()
    amp_ctx = torch.autocast("cuda", dtype=torch.bfloat16) if use_bf16 else torch.autocast("cpu", enabled=False)
    print(f"Mixed precision: {'bf16' if use_bf16 else 'fp32'}")

    n_workers = 2 if torch.cuda.is_available() else 0

    train_data = Path(args.data) if args.data else TRAIN_DATA
    valid_data = Path(args.valid) if args.valid else VALID_DATA
    print("Loading dataset …")
    print(f"  training data: {train_data}")
    train_loader = make_loader(
        train_data, SP_MODEL,
        max_tokens=cfg["max_tokens"],
        max_seq_len=cfg["max_seq_len"],
        shuffle=True, num_workers=n_workers,
    )
    valid_loader = make_loader(
        valid_data, SP_MODEL,
        max_tokens=cfg["max_tokens"],
        max_seq_len=cfg["max_seq_len"],
        shuffle=False, num_workers=0,
    )

    torch.serialization.add_safe_globals([ModelConfig])
    model_cfg = MODEL_CONFIG
    init_state = None
    if args.init:
        ckpt = torch.load(args.init, map_location="cpu", weights_only=True)
        model_cfg = ckpt["config"]
        init_state = ckpt["model"]
        print(f"Initialised from {args.init}")

    model = KeyboardLM(model_cfg).to(device)
    if init_state is not None:
        model.load_state_dict(init_state)
    print(f"Model params: {model.n_params:,}")

    # torch.compile needs Triton, which isn't available on Windows by default.
    if os.environ.get("COMPILE", "0" if os.name == "nt" else "1") != "0":
        try:
            model = torch.compile(model)
            print("Using torch.compile (Inductor)")
        except Exception as e:
            print(f"torch.compile failed, using eager mode: {e}")

    optimizer = AdamW(
        model.parameters(),
        lr=cfg["lr"],
        weight_decay=cfg["weight_decay"],
        betas=(0.9, 0.95),
        fused=torch.cuda.is_available(),
    )

    steps_per_epoch = len(train_loader)
    total_steps = steps_per_epoch * cfg["epochs"]
    step = 0
    best_val_loss = float("inf")

    if args.resume:
        ckpt_path = latest_checkpoint(out_dir)
        if ckpt_path is not None:
            ckpt = torch.load(ckpt_path, map_location="cpu", weights_only=False)
            model.load_state_dict(ckpt["model"])
            optimizer.load_state_dict(ckpt["optimizer"])
            step = ckpt["step"]
            best_val_loss = ckpt.get("best_val_loss", best_val_loss)
            print(f"Resumed from {ckpt_path} at step {step}")

    print(f"{steps_per_epoch:,} steps/epoch × {cfg['epochs']} epochs = {total_steps:,} steps")

    def save_best(val_loss: float) -> None:
        nonlocal best_val_loss
        if val_loss < best_val_loss:
            best_val_loss = val_loss
            torch.save({"step": step, "model": model.state_dict(),
                        "config": model_cfg}, out_dir / "best.pt")
            print(f"[best] val_loss={best_val_loss:.4f} → {out_dir / 'best.pt'}", flush=True)

    model.train()
    t_start = time.time()
    tokens_since_log = 0
    t_log = time.time()
    start_epoch = step // steps_per_epoch + 1
    skip_batches = step % steps_per_epoch

    for epoch in range(start_epoch, cfg["epochs"] + 1):
        for batch_idx, (x, y) in enumerate(train_loader):
            if skip_batches:
                skip_batches -= 1
                continue
            x = x.to(device, non_blocking=True)
            y = y.to(device, non_blocking=True)
            tokens_since_log += int((y != -1).sum())

            lr = cosine_lr(step, cfg["warmup_steps"], total_steps, cfg["lr"], cfg["min_lr"])
            for pg in optimizer.param_groups:
                pg["lr"] = lr

            with amp_ctx:
                _, loss = model(x, targets=y)

            optimizer.zero_grad(set_to_none=True)
            loss.backward()
            torch.nn.utils.clip_grad_norm_(model.parameters(), cfg["grad_clip"])
            optimizer.step()
            step += 1

            if step % cfg["log_every"] == 0:
                now = time.time()
                tok_s = tokens_since_log / (now - t_log)
                done = step / total_steps
                eta_h = (now - t_start) / max(done, 1e-9) * (1 - done) / 3600 if step > 50 else 0
                print(f"epoch={epoch} step={step}/{total_steps} loss={loss.item():.4f} "
                      f"lr={lr:.2e} tok/s={tok_s:,.0f} eta={eta_h:.1f}h", flush=True)
                tokens_since_log = 0
                t_log = now

            if step % cfg["valid_every"] == 0:
                val = evaluate(model, valid_loader, device, amp_ctx, cfg["valid_batches"])
                print(f"[valid] step={step} val_loss={val:.4f}", flush=True)
                save_best(val)

            if step % cfg["save_every"] == 0:
                ckpt = out_dir / f"step_{step:07d}.pt"
                torch.save({"step": step, "model": model.state_dict(), "config": model_cfg,
                            "optimizer": optimizer.state_dict(),
                            "best_val_loss": best_val_loss}, ckpt)
                for old in sorted(out_dir.glob("step_*.pt"))[:-2]:
                    old.unlink()
                print(f"[checkpoint] {ckpt}", flush=True)

        val = evaluate(model, valid_loader, device, amp_ctx, 10_000)
        print(f"[epoch {epoch}] val_loss={val:.4f}", flush=True)
        save_best(val)

    print(f"Training complete in {(time.time() - t_start) / 3600:.2f}h. best val_loss={best_val_loss:.4f}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", default=str(DEFAULT_OUT))
    parser.add_argument("--data", help="training text file (default: correction_train.txt)")
    parser.add_argument("--valid", help="validation text file (default: valid.txt)")
    parser.add_argument("--init", help="checkpoint to start from (fine-tuning)")
    parser.add_argument("--epochs", type=int)
    parser.add_argument("--lr", type=float)
    parser.add_argument("--warmup", type=int)
    parser.add_argument("--max-tokens", type=int)
    parser.add_argument("--resume", action="store_true")
    train(parser.parse_args())
